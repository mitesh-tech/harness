def test_regenerate_keeps_your_rules_and_overwrites_generated_files(shop):
    folder = confirmed_run(shop, "add_review")
    run_generate(shop, folder, in_place=True)
    rules = shop / "app/rules/add_review.py"
    rules.write_text(rules.read_text() + "    # my rule\n")
    again = run_generate(shop, folder, in_place=True)
    assert again.ok
    assert "app/rules/add_review.py" in again.kept
    assert "# my rule" in rules.read_text()


