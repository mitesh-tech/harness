def test_confirm_blocks_open_questions_and_placeholders(shop):
    report = validate_project(shop)
    folder = resolve_service(report, "add_review").folder
    spec = folder / "spec.yaml"
    text = spec.read_text().replace("open_questions: []", "open_questions:\n- Which verb?")
    spec.write_text(
        text.replace("path: /books/{book_id}/reviews\n", "path: /books/{book_id}/<verb>\n", 1)
    )
    with pytest.raises(ResolveError) as problem:
        confirm(report, folder, approve=True)
    assert "open question: Which verb?" in str(problem.value)
    assert "api.path still has <verb>" in str(problem.value)


def test_reject(shop):
    report = validate_project(shop)
    folder = resolve_service(report, "add_review").folder
    assert confirm(report, folder, approve=False)["status"] == "rejected"
    assert read_spec(folder)["status"] == "rejected"


def test_cli_confirm_and_generate(shop):
    report = validate_project(shop)
    run_id = resolve_service(report, "add_review").folder.name
    shown = runner.invoke(app, ["confirm", run_id, "-p", str(shop)])
    assert shown.exit_code == 0, shown.output
    assert "Tests     4 cases" in shown.output
    approved = runner.invoke(app, ["confirm", run_id, "--approve", "-p", str(shop)])
    assert "spec confirmed" in approved.output
    assert (find_run(report, run_id) / ".confirmed").is_file()
    done = runner.invoke(app, ["generate", run_id, "--in-place", "-p", str(shop)])
    assert done.exit_code == 0, done.output
    assert "before  4 failing, 0 passing" in done.output
    assert "after   4 passing, 0 failing" in done.output


def test_cli_generate_stops_with_the_reason(shop):
    report = validate_project(shop)
    run_id = resolve_service(report, "add_book").folder.name
