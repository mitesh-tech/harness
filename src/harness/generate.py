"""Generate code from a confirmed spec: tests first, then the code that makes them pass.

The same for every factory and pack. The factory's design code says which files
a spec becomes (generation_plan); this module renders them, checks it may write
each one, registers routers and models between the markers in the project's
own files, runs the tests before and after, and records what it wrote in
.harness/generated.yaml.

By default it writes into a new git worktree on its own branch, so your working
tree is untouched until you merge; `in_place` writes into the project itself.
"""

import ast
import hashlib
import re
import subprocess
import tempfile
import xml.etree.ElementTree as ET
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined

from harness.datasources import SOURCES_DIR
from harness.knowledge.validate import Report
from harness.packs import Pack, installed_packs
from harness.resolve import confirmed_spec, factory_design
from harness.trace import Event, Trace

REGISTRY = "generated.yaml"  # in the knowledge folder: every generated file and its hash
HEADER = "# Generated by harness: change the spec, not this file.\n# run {run}, spec {spec}"

Runner = Callable[..., subprocess.CompletedProcess]


class GenerateError(RuntimeError):
    """Generation stopped; the message says why and what to do."""


@dataclass
class TestRun:
    passed: list[str] = field(default_factory=list)
    failed: list[str] = field(default_factory=list)
    output: str = ""
    collected: bool = True  # False: the test file could not even be loaded

    @property
    def total(self) -> int:
        return len(self.passed) + len(self.failed)


@dataclass
class Generation:
    workspace: Path  # the project folder the code was written into
    branch: str | None  # the worktree's branch, or None when in place
    written: list[str] = field(default_factory=list)
    kept: list[str] = field(default_factory=list)  # existing files left as they are
    red: TestRun = field(default_factory=TestRun)  # before the code: should all fail
    green: TestRun = field(default_factory=TestRun)  # after: should all pass
    test_file: str = ""

    @property
    def ok(self) -> bool:
        return self.green.total > 0 and not self.green.failed


def generate(
    report: Report, folder: Path, in_place: bool = False, run: Runner = subprocess.run
) -> Generation:
    spec, digest = confirmed_spec(report, folder)
    packs = installed_packs()
    pack = packs.get(report.settings.pack)
    if pack is None:
        raise GenerateError(
            f"pack '{report.settings.pack}' is not installed (installed: {', '.join(packs)})"
        )
    factory = report.factories[spec["factory"]]
    templates = {
        "factory": factory.factory.root / "templates" / pack.name,
        "source": SOURCES_DIR / spec["data"]["type"] / "templates" / pack.name,
        "pack": pack.templates,
    }
    plan = factory_design(factory).generation_plan(spec, pack, templates)

    project, branch = _workspace(report, folder.name, spec, in_place, run)
    result = Generation(project, branch)
    knowledge = project / report.settings.knowledge
    registry = _load_registry(knowledge / REGISTRY)
    header = HEADER.format(run=folder.name, spec=digest[:19])
    environment = Environment(
        loader=FileSystemLoader("/"),
        undefined=StrictUndefined,
        keep_trailing_newline=True,
        trim_blocks=False,
    )

    files = plan["files"]
    model = next((f for f in files if f["kind"] == "model"), None)
    if model is not None and _hand_written(project / model["target"], model["target"], registry):
        _check_model(project / model["target"], spec, model)
        files = [f for f in files if f is not model]
        result.kept.append(model["target"])
        plan["register"]["models"] = []
    for item in files:
        _check_may_write(project, item, registry)

    # 1. tests first: they must fail while the code doesn't exist
    tests = [f for f in files if f["kind"] == "test"]
    for item in tests:
        _write(project, item, environment, header, registry, folder.name, digest, result)
    result.test_file = tests[0]["target"] if tests else ""
    result.red = _run_tests(project, pack, result.test_file, run)
    if not result.red.collected:
        raise GenerateError(
            f"the tests generated from the spec can't be loaded, so no code was written:\n"
            f"{result.red.output}"
        )

    # 2. then the code, registered between the markers
    for item in files:
        if item["kind"] != "test":
            _write(project, item, environment, header, registry, folder.name, digest, result)
    _register(project / pack.manifest.registration.routers, plan["register"]["routers"], pack)
    _register(project / pack.manifest.registration.models, plan["register"]["models"], pack)
    result.green = _run_tests(project, pack, result.test_file, run)

    knowledge.mkdir(parents=True, exist_ok=True)
    (knowledge / REGISTRY).write_text(_registry_text(registry))
    _trace(folder, result)
    if branch and result.ok:
        message = f"harness: generate {spec['service']['name']} (run {folder.name})"
        _git(project, ["add", "-A", "."], run)
        _git(project, ["commit", "-q", "-m", message], run)
    return result


# ── Where the code is written ───────────────────────────────────────


def _workspace(report: Report, run_id: str, spec: dict, in_place: bool, run: Runner):
    if in_place:
        return report.root, None
    top = _git(report.root, ["rev-parse", "--show-toplevel"], run).strip()
    if not top:
        raise GenerateError("the project is not in a git repository; use --in-place")
    repo = Path(top)
    service = re.sub(r"[^a-z0-9_]+", "-", spec["service"]["name"])
    branch = f"harness/{run_id}-{service}"
    path = repo.parent / f"{repo.name}-harness" / run_id
    if path.exists():
        raise GenerateError(
            f"{path} already exists from an earlier generate; remove it with "
            f"`git worktree remove {path}` (and its branch {branch}) to generate again"
        )
    _git(repo, ["worktree", "add", "-q", "-b", branch, str(path), "HEAD"], run)
    return path / report.root.relative_to(repo), branch


def _git(cwd: Path, args: list[str], run: Runner) -> str:
    done = run(["git", *args], cwd=cwd, capture_output=True, text=True)
    if done.returncode != 0:
        raise GenerateError(f"git {' '.join(args)} failed: {done.stderr.strip()}")
    return done.stdout


# ── May a file be written? ──────────────────────────────────────────


def _hand_written(path: Path, target: str, registry: dict) -> bool:
    return path.exists() and target not in registry


def _check_may_write(project: Path, item: dict, registry: dict) -> None:
    path = project / item["target"]
    if item["owner"] != "harness" or not path.exists():
        return  # yours and shared files are only created when missing
    known = registry.get(item["target"])
    if known is None:
        raise GenerateError(
            f"{item['target']} exists and was not generated by harness; "
            "move it away or rename the service"
        )
    if known["sha256"] != _hash(path.read_text()):
        raise GenerateError(
            f"{item['target']} was edited by hand after it was generated; keep your edits "
            "in the spec or the rules hook, then restore the file to generate again"
        )


def _check_model(path: Path, spec: dict, item: dict) -> None:
    """A hand-written model is reused only if it has every column data.yaml maps."""
    tree = ast.parse(path.read_text())
    names = {
        node.target.id
        for cls in tree.body
        if isinstance(cls, ast.ClassDef) and cls.name == spec["target"]
        for node in cls.body
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name)
    }
    needed = list(spec["data"]["columns"])
    parent_key = spec["data"].get("parent_key")
    if parent_key:
        needed.append(parent_key)
    missing = [name for name in needed if name not in names]
    if missing:
        raise GenerateError(
            f"{item['target']} (written by hand) has no {', '.join(missing)}, which "
            "data.yaml maps; add the column(s) to the model, or mark the attribute "
            "`stored: false` in data.yaml"
        )


# ── Writing ─────────────────────────────────────────────────────────


def _write(project, item, environment, header, registry, run_id, digest, result) -> None:
    path = project / item["target"]
    if item["owner"] in ("you", "shared") and path.exists():
        result.kept.append(item["target"])
        return
    if item["template"] is None:
        text = ""
    else:
        template = environment.get_template(str(item["template"]))
        text = template.render(**item["context"], header=header)
        text = text.strip() + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    result.written.append(item["target"])
    if item["owner"] != "you":
        registry[item["target"]] = {"run": run_id, "spec": digest, "sha256": _hash(text)}


def _register(path: Path, lines: list[str], pack: Pack) -> None:
    """Add lines between the markers in one of the project's own files."""
    if not lines:
        return
    start, end = pack.manifest.markers["start"], pack.manifest.markers["end"]
    text = path.read_text()
    if start not in text or end not in text:
        listed = "\n    ".join(lines)
        raise GenerateError(
            f"{path.name} has no harness markers; add these two lines where generated "
            f"code should be registered, then generate again:\n    {start}\n    {end}\n"
            f"(the generated lines will be:\n    {listed})"
        )
    head, rest = text.split(start, 1)
    block, tail = rest.split(end, 1)
    indent = head[head.rfind("\n") + 1 :]
    present = [line.strip() for line in block.splitlines() if line.strip()]
    for line in lines:
        if line not in present:
            present.append(line)
    # a blank line before the end marker keeps import sorters (isort, ruff) content
    inner = "".join(f"\n{indent}{line}" for line in present) + ("\n" if present else "")
    path.write_text(f"{head}{start}{inner}\n{indent}{end}{tail}")


# ── Running the tests ───────────────────────────────────────────────


def _run_tests(project: Path, pack: Pack, test_file: str, run: Runner) -> TestRun:
    command = pack.manifest.commands.get("test")
    if not command or not test_file:
        return TestRun()
    with tempfile.TemporaryDirectory() as tmp:
        junit = Path(tmp) / "junit.xml"
        done = run(
            [*command, test_file, f"--junitxml={junit}"],
            cwd=project,
            capture_output=True,
            text=True,
        )
        result = TestRun(output=(done.stdout + done.stderr)[-4000:])
        if not junit.exists():
            result.collected = False
            return result
        for case in ET.parse(junit).getroot().iter("testcase"):
            failed = any(child.tag in ("failure", "error") for child in case)
            (result.failed if failed else result.passed).append(case.get("name"))
        if result.total == 1 and result.failed and "." in result.failed[0]:
            result.collected = False  # pytest reports a file it can't load as one error
    return result


# ── Records ─────────────────────────────────────────────────────────


def _hash(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def _load_registry(path: Path) -> dict:
    if not path.is_file():
        return {}
    return (yaml.safe_load(path.read_text()) or {}).get("files", {})


def _registry_text(registry: dict) -> str:
    return (
        "# Files harness generated, with the spec they came from and their hash.\n"
        "# `harness generate` overwrites a file only if its hash still matches.\n\n"
        + yaml.safe_dump({"files": dict(sorted(registry.items()))}, sort_keys=False)
    )


def _trace(folder: Path, result: Generation) -> None:
    path = folder / "trace.jsonl"
    trace = Trace.from_jsonl(path.read_text())
    for target in result.written:
        trace.events.append(
            Event(stage="generate", step=target, by="rule", answer="written", reason="template")
        )
    for name, tests in (("before the code", result.red), ("after the code", result.green)):
        trace.events.append(
            Event(
                stage="generate",
                step=f"tests {name}",
                by="rule",
                answer=f"{len(tests.passed)} passed, {len(tests.failed)} failed",
                reason=result.test_file,
            )
        )
    path.write_text(trace.to_jsonl())
