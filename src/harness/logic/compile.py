"""Turn validated domain + technical knowledge into a Prolog program.

Prolog reads uppercase words as variables, so entity names are written in
lowercase snake form (Book -> book, BookAuthor -> book_author). `NameMap`
maps them back for messages.

Every bridge rule becomes Prolog clauses whose last argument is the rule id,
so each derived decision carries its own proof.
"""

